// Command openapi renders docs/openapi.yaml from the routes registered in
// internal/api/server.go. Run `go generate ./internal/api` after adding a route;
// `-check` fails when the committed file is stale.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"
	"unicode"
)

var routePattern = regexp.MustCompile(`m\.HandleFunc\("([A-Z]+) ([^"]+)", (.+)\)`)

type route struct {
	method  string
	path    string
	handler string
	authed  bool
	tag     string
	params  []string
}

func main() {
	src := flag.String("src", "internal/api/server.go", "route source")
	out := flag.String("out", "docs/openapi.yaml", "output file")
	versionFile := flag.String("version-file", "VERSION", "file holding the release version")
	check := flag.Bool("check", false, "verify the output is current instead of writing")
	flag.Parse()

	raw, err := os.ReadFile(*src)
	if err != nil {
		fail(err)
	}
	routes, err := parse(string(raw))
	if err != nil {
		fail(err)
	}
	doc := render(routes, version(*versionFile))
	if *check {
		current, err := os.ReadFile(*out)
		if err != nil || !bytes.Equal(current, doc) {
			fail(fmt.Errorf("%s is stale: run go generate ./internal/api", *out))
		}
		return
	}
	if err := os.WriteFile(*out, doc, 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("wrote %s with %d operations\n", *out, len(routes))
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "openapi:", err)
	os.Exit(1)
}

func version(file string) string {
	if raw, err := os.ReadFile(file); err == nil {
		return strings.TrimSpace(string(raw))
	}
	return "dev"
}

func parse(src string) ([]route, error) {
	var routes []route
	for _, m := range routePattern.FindAllStringSubmatch(src, -1) {
		r := route{method: m[1], path: m[2], authed: strings.Contains(m[3], "authed(")}
		call := regexp.MustCompile(`s\.(\w+)(?:\(|$)`).FindStringSubmatch(m[3])
		if call == nil {
			continue
		}
		r.handler = call[1]
		segs := strings.Split(strings.TrimPrefix(r.path, "/"), "/")
		if len(segs) > 1 && segs[0] == "api" {
			r.tag = segs[1]
		} else if len(segs) > 0 {
			r.tag = segs[0]
		}
		for _, part := range segs {
			if strings.HasPrefix(part, "{") {
				r.params = append(r.params, strings.Trim(part, "{}"))
			}
		}
		routes = append(routes, r)
	}
	if len(routes) == 0 {
		return nil, fmt.Errorf("no routes found in %s", src)
	}
	sort.Slice(routes, func(i, j int) bool {
		if routes[i].path == routes[j].path {
			return routes[i].method < routes[j].method
		}
		return routes[i].path < routes[j].path
	})
	return routes, nil
}

func humanize(name string) string {
	var b strings.Builder
	for i, r := range name {
		if unicode.IsUpper(r) && i > 0 {
			b.WriteByte(' ')
		}
		b.WriteRune(unicode.ToLower(r))
	}
	return b.String()
}

func render(routes []route, version string) []byte {
	var b strings.Builder
	b.WriteString("# Generated by tools/openapi; do not edit by hand.\n")
	b.WriteString("openapi: 3.0.3\ninfo:\n  title: WAF-Proxy admin API\n  version: \"" + version + "\"\n")
	b.WriteString("  description: |\n    Routes registered by the admin console. Every `/api` route except setup,\n    login, health and version requires the session cookie and, for mutations,\n    the `X-CSRF-Token` header.\n")
	b.WriteString("servers:\n  - url: http://127.0.0.1:8080\n    description: Admin console (WAFPROXY_LISTEN_GUI)\n")
	b.WriteString("components:\n  securitySchemes:\n    sessionCookie:\n      type: apiKey\n      in: cookie\n      name: __wfp_sid\n")
	b.WriteString("paths:\n")
	lastPath := ""
	for _, r := range routes {
		if r.path != lastPath {
			b.WriteString("  " + r.path + ":\n")
			lastPath = r.path
		}
		b.WriteString("    " + strings.ToLower(r.method) + ":\n")
		b.WriteString("      operationId: " + r.handler + "\n")
		b.WriteString("      tags: [" + r.tag + "]\n")
		b.WriteString("      summary: " + strings.Title(humanize(r.handler)) + "\n")
		if r.authed {
			b.WriteString("      security:\n        - sessionCookie: []\n")
		} else {
			b.WriteString("      security: []\n")
		}
		if len(r.params) > 0 {
			b.WriteString("      parameters:\n")
			for _, p := range r.params {
				b.WriteString("        - name: " + p + "\n          in: path\n          required: true\n          schema: {type: integer}\n")
			}
		}
		b.WriteString("      responses:\n        \"200\":\n          description: Success\n")
		if r.authed {
			b.WriteString("        \"401\":\n          description: Missing or expired session\n")
		}
	}
	return []byte(b.String())
}
